/// Generates the configuration methods shared by the macro `Builder` and `Poring`.
macro_rules! config_methods {
    () => {
        /// Overrides parser/server limits.
        pub fn limits(mut self, limits: $crate::app::Limits) -> Self {
            self.cfg.limits = limits;
            self
        }

        /// Enables runtime flow recording (sampling 1 in `sample_every`). Requires the
        /// `trace-flow` feature; without it `build()` logs a warning and nothing is recorded.
        pub fn flow_recording(mut self, cfg: $crate::flow::FlowConfig) -> Self {
            self.cfg.flow = cfg;
            self
        }

        /// Sets the security headers added to responses.
        pub fn security_headers(mut self, h: $crate::app::SecurityHeaders) -> Self {
            self.cfg.security_headers = h;
            self
        }

        /// Adds a pre-route request hook. Returning `Some` short-circuits
        /// before routing and before any policy check (maintenance mode, blocklists).
        pub fn on_request(
            mut self,
            f: impl Fn(&http::request::Parts) -> Option<$crate::response::Response> + Send + Sync + 'static,
        ) -> Self {
            self.cfg.on_request.push(Box::new(f));
            self
        }

        /// Adds an after-response hook, run once the response body
        /// has been fully handed to hyper or dropped.
        pub fn on_response(mut self, f: impl Fn(&$crate::app::ResponseInfo) + Send + Sync + 'static) -> Self {
            self.cfg.on_response.push(std::sync::Arc::new(f));
            self
        }

        /// Rewrites framework-generated error responses (404, 405, 401, 403, 413, 415, 422,
        /// 429, 503 and extractor rejections). Application `ApiError`s are not affected.
        pub fn map_errors(
            mut self,
            f: impl Fn(&$crate::error::FrameworkError, $crate::response::Response) -> $crate::response::Response
            + Send
            + Sync
            + 'static,
        ) -> Self {
            self.cfg.error_mapper = Some(Box::new(f));
            self
        }

        /// Emits/propagates `x-request-id` (default: on).
        pub fn request_ids(mut self, on: bool) -> Self {
            self.cfg.request_ids = on;
            self
        }

        /// Proxies (addresses or CIDR networks such as `"10.0.0.0/8"`) whose
        /// `X-Forwarded-For` entries identify the client for IP-keyed rate limits. Without
        /// this the TCP peer address is used and the header is ignored. Invalid entries are
        /// reported by `build()`. See [`crate::policy::proxy`].
        pub fn trusted_proxies<I, T>(mut self, proxies: I) -> Self
        where
            I: IntoIterator<Item = T>,
            T: Into<String>,
        {
            self.cfg.trusted_proxies.extend(proxies.into_iter().map(Into::into));
            self
        }

        /// Formerly trusted the left-most `X-Forwarded-For` entry from any peer, which let
        /// clients choose their own rate-limit identity. `true` is now rejected by `build()`.
        #[deprecated(
            since = "0.1.2",
            note = "trusting X-Forwarded-For from any peer is spoofable; use `trusted_proxies([..])`"
        )]
        pub fn trust_forwarded_for(mut self, on: bool) -> Self {
            self.cfg.legacy_forwarded_for = on;
            self
        }

        /// An app-wide rate limit enforced *in addition to* every route's own limit, with one
        /// shared bucket per client. A route-level policy cannot opt out of it. A
        /// principal-keyed ceiling covers authenticated routes only.
        pub fn rate_limit_ceiling(mut self, limit: $crate::policy::RateLimit) -> Self {
            self.cfg.rate_limit_ceiling = Some(limit);
            self
        }

        /// Origins allowed to open WebSocket connections, in addition to same-origin and
        /// explicit CORS origins. See [`crate::policy::WsOrigins`]; invalid entries are
        /// reported by `build()`.
        pub fn ws_origins(mut self, origins: $crate::policy::WsOrigins) -> Self {
            self.cfg.ws_origins = origins;
            self
        }

        /// Registers a dynamic (runtime-validated, not compile-time-verified) route.
        pub fn mount_dynamic(mut self, route: $crate::dynamic::DynamicRoute) -> Self {
            self.cfg.dynamic.push(route);
            self
        }
    };
}
pub(crate) use config_methods;

/// Typestate builder generated per app by `poring_app!` (`Api::builder()`).
///
/// `St`/`Au` track whether the declared state and authenticator were supplied; the
/// server can only be built when both are `Provided` (compile-time check).
pub struct Builder<A: AppSpec, St, Au> {
    state: St,
    auth: Au,
    cfg: BuilderConfig<A::State>,
    _app: std::marker::PhantomData<fn() -> A>,
}

impl<A: AppSpec, St, Au> std::fmt::Debug for Builder<A, St, Au> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Builder")
            .field("app", &A::APP.name)
            .finish_non_exhaustive()
    }
}

impl<A: AppSpec, St, Au> Builder<A, St, Au> {
    #[doc(hidden)]
    pub fn __new(state: St, auth: Au) -> Self {
        Builder {
            state,
            auth,
            cfg: BuilderConfig::default(),
            _app: std::marker::PhantomData,
        }
    }

    config_methods!();

    /// Mounts a group of fluent routes on this macro-declared app. The group is validated
    /// when the app is built (not by `poring_app!`'s compile-time checks).
    #[track_caller]
    pub fn group(
        mut self,
        prefix: &str,
        f: impl FnOnce(Group<A::State>) -> Group<A::State>,
    ) -> Self {
        let loc = std::panic::Location::caller();
        let g = f(Group::new(
            prefix,
            SourceLoc {
                file: loc.file().replace('\\', "/"),
                line: loc.line(),
            },
        ));
        self.cfg.native.add_group(g);
        self
    }

    fn push_route(mut self, route: NativeRoute<A::State>) -> Self {
        self.cfg.native.routes.push((None, route));
        self
    }
}

/// Fluent route registration on a macro-declared app (`Api::builder().get(..)`).
///
/// Such routes share the app's state, authenticator, global hooks and runtime pipeline,
/// but they are checked when the app is built rather than by `poring_app!` at compile time.
impl<A: AppSpec, St, Au> Builder<A, St, Au>
where
    A::State: Send + Sync + 'static,
{
    route_methods!(A::State);
}

impl<A: AppSpec, Au> Builder<A, Missing, Au> {
    /// Supplies the app state declared in `poring_app!`.
    pub fn state(self, state: A::State) -> Builder<A, Provided<A::State>, Au> {
        Builder {
            state: Provided(state),
            auth: self.auth,
            cfg: self.cfg,
            _app: std::marker::PhantomData,
        }
    }
}

impl<A: AppSpec, St> Builder<A, St, Missing> {
    /// Supplies the authenticator declared in `poring_app!`.
    pub fn authenticator(self, auth: A::Auth) -> Builder<A, St, Provided<A::Auth>> {
        Builder {
            state: self.state,
            auth: Provided(auth),
            cfg: self.cfg,
            _app: std::marker::PhantomData,
        }
    }
}

/// Error starting an app.
#[derive(Debug, thiserror::Error)]
pub enum StartupError {
    /// Routing table could not be built.
    #[error(transparent)]
    Router(#[from] RouterError),
    /// A dynamic route violates policy or path rules.
    #[error("dynamic route `{method} {path}`: {reason}")]
    DynamicRoute {
        /// Method.
        method: &'static str,
        /// Path.
        path: String,
        /// Reason.
        reason: String,
    },
    /// A route failed runtime policy resolution. Prevented at compile time for
    /// `poring_app!` routes; reported here for fluent and dynamic routes.
    #[error("route `{0}`: {1}")]
    Policy(String, String),
    /// A fluent route, group or app-level setting is invalid.
    #[error("{0}")]
    Config(String),
    /// [`Poring::run`](crate::fluent::Poring::run) was called inside an existing Tokio runtime.
    #[error(
        "`run()` cannot start a Tokio runtime inside another one; use `.listen(addr).await` from async code instead"
    )]
    NestedRuntime,
    /// I/O error binding the listener.
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

impl<A: AppSpec, St, Au> Builder<A, St, Au> {
    /// Builds the immutable app: resolves effective policies, builds the router and the
    /// manifest. Fails on dynamic-route violations or router conflicts.
    ///
    /// Only callable once the declared state and authenticator have been supplied
    /// (compile-time check).
    pub fn build(self) -> Result<App<A>, StartupError>
    where
        St: StateReady<A::State>,
        Au: AuthReady<A::Auth>,
    {
        App::from_parts(
            self.state.into_inner(),
            self.auth.into_inner(),
            self.cfg,
            AppLevel::from_descriptor(&A::APP),
        )
    }

    /// Builds and serves on `addr` until Ctrl-C, then drains gracefully.
    pub async fn listen(self, addr: impl tokio::net::ToSocketAddrs) -> Result<(), StartupError>
    where
        St: StateReady<A::State>,
        Au: AuthReady<A::Auth>,
    {
        self.build()?.listen(addr).await
    }
}

/// A built, immutable Poring application.
pub struct App<A: AppSpec> {
    inner: Arc<AppInner<A>>,
}

impl<A: AppSpec> Clone for App<A> {
    fn clone(&self) -> Self {
        App {
            inner: self.inner.clone(),
        }
    }
}

impl<A: AppSpec> std::fmt::Debug for App<A> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("App")
            .field("name", &self.inner.name)
            .field("routes", &self.inner.routes.len())
            .finish()
    }
}

impl<A: AppSpec> App<A> {
    pub(crate) fn from_parts(
        state: A::State,
        auth: A::Auth,
        cfg: BuilderConfig<A::State>,
        mut level: AppLevel,
    ) -> Result<Self, StartupError> {
        let config = |e: String| StartupError::Config(format!("app `{}`: {e}", level.name));
        if let Some(c) = &level.cors {
            c.validate().map_err(config)?;
        }
        if cfg.legacy_forwarded_for {
            return Err(config(
                "`trust_forwarded_for(true)` trusted X-Forwarded-For from any client; \
                 list your proxies with `trusted_proxies([..])` instead"
                    .into(),
            ));
        }
        let ws_origins = crate::policy::ws_origin::WsOriginPolicy::from_config(
            &cfg.ws_origins,
            level.auth_uses_cookies,
        )
        .map_err(config)?;
        let proxies = TrustedProxies::parse(&cfg.trusted_proxies)
            .map_err(|e| config(format!("trusted_proxies: {e}")))?;
        RateLimiter::validate_capacity(cfg.limits.rate_limit_keys).map_err(config)?;
        if let Some(ceiling) = cfg.rate_limit_ceiling {
            let spec = ceiling
                .to_spec()
                .map_err(|e| config(format!("rate_limit_ceiling: {e}")))?;
            if spec.scope == crate::policy::RateScope::Group {
                return Err(config("rate_limit_ceiling cannot be group-scoped".into()));
            }
            level.ceiling = Some(spec);
        }
        if let Some(e) = cfg.native.errors.first() {
            return Err(config(e.clone()));
        }
        let planned = plan::plan::<A>(&level, cfg.native, cfg.dynamic)?;
        let router = Router::build(&planned.routes)?;
        // Per-route WebSocket origin policies, indexed like `routes` (route.index).
        let mut route_ws_origins = Vec::with_capacity(planned.routes.len());
        for (i, r) in planned.routes.iter().enumerate() {
            if r.index as usize != i {
                return Err(config(format!("internal: route index {} at {i}", r.index)));
            }
            route_ws_origins.push(match &r.policy.ws_origins {
                Some(o) => Some(
                    crate::policy::ws_origin::WsOriginPolicy::from_config(
                        o,
                        level.auth_uses_cookies,
                    )
                    .map_err(|e| config(format!("route `{}`: {e}", r.id)))?,
                ),
                None => None,
            });
        }
        Ok(App {
            inner: Arc::new(AppInner {
                state,
                auth,
                name: level.name,
                router,
                limiter: RateLimiter::new(cfg.limits.rate_limit_keys),
                recorder: {
                    if !cfg!(feature = "trace-flow") && cfg.flow.sample_every != 0 {
                        tracing::warn!(
                            "flow recording was requested but poring was built without the                              `trace-flow` feature; nothing will be recorded"
                        );
                    }
                    FlowRecorder::new(cfg.flow)
                },
                cors: level.cors.as_ref().map(CorsRuntime::from_cors),
                routes: planned.routes,
                native: planned.native,
                native_groups: planned.native_groups,
                native_hooks: planned.native_hooks,
                docs: planned.docs,
                limits: cfg.limits,
                security_headers: cfg.security_headers,
                on_request: cfg.on_request,
                on_response: cfg.on_response.into(),
                error_mapper: cfg.error_mapper,
                request_ids: cfg.request_ids,
                proxies,
                ws_origins,
                route_ws_origins: route_ws_origins.into_boxed_slice(),
                #[cfg(feature = "websocket")]
                ws_counters: Default::default(),
                manifest_base: planned.manifest,
            }),
        })
    }

    /// A snapshot of this app's WebSocket counters, summed over every listener serving it
    /// (`websocket` feature). See [`crate::ws::WsStats`].
    #[cfg(feature = "websocket")]
    pub fn ws_stats(&self) -> crate::ws::WsStats {
        self.inner.ws_counters.snapshot()
    }

    /// Serves on `addr` until Ctrl-C, then drains gracefully.
    pub async fn listen(self, addr: impl tokio::net::ToSocketAddrs) -> Result<(), StartupError> {
        let listener = tokio::net::TcpListener::bind(addr).await?;
        tracing::info!(app = %self.inner.name, addr = ?listener.local_addr().ok(), "poring listening");
        self.serve(listener, async {
            // If signal registration fails we keep serving; shutdown can still happen
            // through process termination.
            if tokio::signal::ctrl_c().await.is_err() {
                std::future::pending::<()>().await;
            }
        })
        .await?;
        Ok(())
    }

    /// The OpenAPI 3.1 document of every route served by this app (macro, fluent and
    /// dynamic). Dynamic routes are documented with an opaque body.
    #[cfg(feature = "openapi")]
    pub fn openapi(&self, info: &crate::openapi::Info) -> serde_json::Value {
        crate::openapi::document(info, &self.manifest(), &self.inner.docs)
    }

    /// The application manifest (effective policies, hooks, extractors; dynamic routes
    /// include their current endpoint metadata such as the live guest version).
    pub fn manifest(&self) -> Manifest {
        let mut m = self.inner.manifest_base.clone();
        for (entry, rt) in m.routes.iter_mut().zip(&self.inner.routes) {
            if let Target::Dynamic(ep) = &rt.target {
                entry.meta = ep.metadata();
            }
        }
        m
    }

    /// The static flow graph (optionally for one route: `"GET /users/{id}"`, ID or handler).
    pub fn graph(&self, route: Option<&str>) -> Option<crate::contract::FlowGraph> {
        crate::contract::build_graph(&self.manifest(), route)
    }

    /// The runtime flow recorder (traces are only recorded if enabled on the builder).
    pub fn flow(&self) -> &FlowRecorder {
        &self.inner.recorder
    }

    /// The rate limiter (exposed for metrics).
    pub fn rate_limiter(&self) -> &RateLimiter {
        &self.inner.limiter
    }

    /// Handles one request in-process (used by the server and by tests).
    pub async fn handle(&self, req: Request<ReqBody>, peer: Option<SocketAddr>) -> Response {
        self.inner.handle(req, peer).await
    }
}
