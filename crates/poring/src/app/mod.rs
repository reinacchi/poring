/// Implemented by `poring_app!` for the generated app type. Not intended to be
/// implemented by hand: the macro also emits the compile-time checks that make the
/// implementation trustworthy.
pub trait AppSpec: Sized + Send + Sync + 'static {
    /// App state type.
    type State: Send + Sync + 'static;
    /// Authenticator type (`NoAuth` if none declared).
    type Auth: Authenticator;
    /// The whole-app descriptor (checked by `check_app` during const evaluation).
    const APP: AppDescriptor;

    /// Runs hooks, extractors and the handler of static route `index`. Only reachable
    /// through the runtime pipeline because `Ctx` has no public constructor.
    fn dispatch<'a, 'c>(
        index: u16,
        cx: &'c mut Ctx<'a, Self::State>,
    ) -> impl Future<Output = Response> + Send + 'c;

    /// Runs the app's global before hooks for a natively registered route (fluent routes
    /// mounted on a macro app). Generated by `poring_app!`; no hooks by default.
    #[doc(hidden)]
    fn __global_before<'a, 'c>(
        cx: &'c mut Ctx<'a, Self::State>,
    ) -> impl Future<Output = Result<(), Response>> + Send + 'c {
        let _ = cx;
        std::future::ready(Ok(()))
    }

    /// Runs the app's global after hooks for a natively registered route.
    #[doc(hidden)]
    fn __global_after<'a, 'c>(
        cx: &'c mut Ctx<'a, Self::State>,
        res: &'c mut Response,
    ) -> impl Future<Output = ()> + Send + 'c {
        let _ = (cx, res);
        std::future::ready(())
    }
}

/// Server and parser limits.
#[derive(Clone, Debug)]
pub struct Limits {
    /// Maximum raw query string length (bytes).
    pub max_query_bytes: usize,
    /// Maximum urlencoded fields in a query string or form body.
    pub max_form_fields: usize,
    /// Maximum concurrent TCP connections per listener (`serve`/`bind`). An upgraded
    /// WebSocket keeps its connection's slot until the session ends.
    pub max_connections: usize,
    /// Maximum concurrently running WebSocket sessions per listener (`websocket`
    /// feature). Checked before `101 Switching Protocols`; when full, handshakes get
    /// `503`. Independent of `max_connections`, which still bounds the TCP connections the
    /// sessions run on.
    pub max_ws_sessions: usize,
    /// Maximum concurrent WebSocket sessions per client IP, per listener (`websocket`
    /// feature). The IP is resolved like the HTTP rate limiter's: the TCP peer, or the
    /// client named by trusted proxies' forwarding headers. Over the limit, handshakes get
    /// `429`. Default `usize::MAX` (no per-IP limit), because clients behind one NAT or
    /// proxy share an address.
    pub max_ws_sessions_per_ip: usize,
    /// Maximum concurrent WebSocket sessions per authenticated principal (identity
    /// subject), per listener. Anonymous sessions are not counted. Over the limit,
    /// handshakes get `429`. Default `usize::MAX` (no limit).
    pub max_ws_sessions_per_principal: usize,
    /// Time allowed for a client to send request headers.
    pub header_read_timeout: Duration,
    /// Grace period for in-flight requests on shutdown.
    pub shutdown_grace: Duration,
    /// Maximum number of rate-limit buckets (one per client and bucket scope), between 1
    /// and [`crate::policy::rate_limit::MAX_KEYS`]. Only fully refilled buckets are
    /// reclaimed; when every bucket is active, new clients get 503 (fail closed).
    pub rate_limit_keys: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Limits {
            max_query_bytes: 8 * 1024,
            max_form_fields: 256,
            max_connections: 10_000,
            max_ws_sessions: 10_000,
            max_ws_sessions_per_ip: usize::MAX,
            max_ws_sessions_per_principal: usize::MAX,
            header_read_timeout: Duration::from_secs(30),
            shutdown_grace: Duration::from_secs(10),
            rate_limit_keys: 100_000,
        }
    }
}

/// Information passed to after-response hooks (no bodies, headers or credentials).
#[derive(Clone, Debug)]
pub struct ResponseInfo {
    /// Correlation ID.
    pub request_id: String,
    /// Matched route ID.
    pub route: Option<String>,
    /// Method.
    pub method: http::Method,
    /// Status.
    pub status: StatusCode,
    /// Time from receive until the body finished (or was dropped).
    pub elapsed: Duration,
    /// How the body ended.
    pub end: BodyEnd,
}

pub(crate) type OnRequest = Box<dyn Fn(&http::request::Parts) -> Option<Response> + Send + Sync>;
pub(crate) type OnResponse = Arc<dyn Fn(&ResponseInfo) + Send + Sync>;
pub(crate) type ErrorMapper = Box<dyn Fn(&FrameworkError, Response) -> Response + Send + Sync>;

/// Typestate marker: a required builder input has not been supplied.
#[derive(Debug, Clone, Copy, Default)]
pub struct Missing;

/// Typestate marker: a required builder input has been supplied.
#[derive(Debug, Clone)]
pub struct Provided<T>(pub(crate) T);

pub(crate) fn provided<T>(t: T) -> Provided<T> {
    Provided(t)
}

/// Implemented only for `Provided<T>`: the app state has been supplied.
#[diagnostic::on_unimplemented(
    message = "the app state has not been provided",
    label = "call `.state(...)` on the builder before starting the server",
    note = "this app declares `state: {T}` in `poring_app!`"
)]
pub trait StateReady<T> {
    #[doc(hidden)]
    fn into_inner(self) -> T;
}
impl<T> StateReady<T> for Provided<T> {
    fn into_inner(self) -> T {
        self.0
    }
}

/// Implemented only for `Provided<T>`: the authenticator has been supplied.
#[diagnostic::on_unimplemented(
    message = "the authenticator has not been provided",
    label = "call `.authenticator(...)` on the builder before starting the server",
    note = "this app declares `auth: {T}` in `poring_app!`; routes requiring authentication cannot run without it"
)]
pub trait AuthReady<T> {
    #[doc(hidden)]
    fn into_inner(self) -> T;
}
impl<T> AuthReady<T> for Provided<T> {
    fn into_inner(self) -> T {
        self.0
    }
}

/// Security response headers added to every response (unless the handler set them).
#[derive(Clone, Debug)]
pub struct SecurityHeaders(pub Vec<(HeaderName, HeaderValue)>);

impl Default for SecurityHeaders {
    /// `X-Content-Type-Options: nosniff` only.
    fn default() -> Self {
        SecurityHeaders(vec![(
            http::header::X_CONTENT_TYPE_OPTIONS,
            HeaderValue::from_static("nosniff"),
        )])
    }
}

impl SecurityHeaders {
    /// API-oriented strict set: nosniff, `X-Frame-Options: DENY`,
    /// `Referrer-Policy: no-referrer`, `Content-Security-Policy: default-src 'none'; frame-ancestors 'none'`.
    /// HSTS is not included because it is only correct behind TLS; add it explicitly.
    pub fn strict_api() -> Self {
        use http::header::*;
        SecurityHeaders(vec![
            (X_CONTENT_TYPE_OPTIONS, HeaderValue::from_static("nosniff")),
            (X_FRAME_OPTIONS, HeaderValue::from_static("DENY")),
            (REFERRER_POLICY, HeaderValue::from_static("no-referrer")),
            (
                CONTENT_SECURITY_POLICY,
                HeaderValue::from_static("default-src 'none'; frame-ancestors 'none'"),
            ),
        ])
    }

    /// Adds a header.
    pub fn with(mut self, name: HeaderName, value: HeaderValue) -> Self {
        self.0.push((name, value));
        self
    }
}

